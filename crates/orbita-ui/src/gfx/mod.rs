//! Графический слой: кадр как список GPU-инстансов.
//!
//! Весь интерфейс за кадр превращается в плоский массив [`Instance`] —
//! «примитивов» фиксированного размера (скруглённый прямоугольник с
//! градиентом, тень, глиф, векторная иконка, стекло, шум). Один и тот же
//! массив рисуют:
//!
//! * GPU-рендерер эмулятора (`emu/orbita-emu`, wgpu + WGSL) — одним
//!   instanced draw-call на пакет, сотни кадров в секунду;
//! * программный растеризатор ядра ([`soft`]) — в UEFI framebuffer.
//!
//! ```text
//! Shell/Apps ──► Painter ──► Frame { instances, batches, segments }
//!                                  │
//!                 ┌────────────────┴───────────────┐
//!                 ▼                                ▼
//!        wgpu (RTX/любой GPU)            soft::SoftRenderer (ядро)
//! ```
//!
//! Формат [`Instance`] — `#[repr(C)]`, это и есть граница между горячо
//! перезагружаемой DLL оболочки и хостом эмулятора.

pub mod painter;
pub mod soft;
pub mod text;

pub use painter::{GlassStyle, Paint, Painter, Shadow};

/// Вид примитива (поле `params[0]` инстанса).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u32)]
pub enum Kind {
    /// Скруглённый прямоугольник: заливка (сплошная/градиент) + рамка.
    Rect = 0,
    /// Размытая тень скруглённого прямоугольника (box-shadow).
    Shadow = 1,
    /// Глиф из атласа шрифтов (покрытие R8 × цвет).
    Glyph = 2,
    /// Векторный контур: обводка/заливка ломаной из `segments`.
    Path = 3,
    /// Стекло: размытый задний план (backdrop-filter) в форме прямоугольника.
    Backdrop = 4,
    /// Зерно шума поверх поверхности (mix-blend-mode: overlay).
    Noise = 5,
}

/// Один примитив кадра. 13 × vec4 = 208 байт, выровнено под GPU.
///
/// Координаты — физические пиксели окна/экрана. Цвета — sRGB, прямая альфа.
#[derive(Clone, Copy, Debug, PartialEq, Default)]
#[repr(C)]
pub struct Instance {
    /// Габарит квада `[x, y, w, h]` (для тени — расширенный на 3σ).
    pub rect: [f32; 4],
    /// Радиусы углов `[tl, tr, br, bl]`.
    pub radii: [f32; 4],
    /// Цвет 0 (сплошная заливка или первая точка градиента).
    pub color0: [f32; 4],
    /// Цвет 1 (средняя точка градиента).
    pub color1: [f32; 4],
    /// Цвет 2 (конечная точка градиента).
    pub color2: [f32; 4],
    /// Цвет рамки.
    pub border: [f32; 4],
    /// `[kind, ширина рамки, сила шума, aux]`; aux: σ тени / ширина
    /// обводки пути / сила размытия стекла (px).
    pub params: [f32; 4],
    /// Градиент: `[тип (0 нет,1 линейный,2 радиальный), x0, y0, позиция средней точки]`.
    pub grad0: [f32; 4],
    /// Градиент: линейный `[x1, y1, конец, _]`; радиальный `[rx, ry, конец, _]`.
    pub grad1: [f32; 4],
    /// Прямоугольник отсечения `[x0, y0, x1, y1]`.
    pub clip: [f32; 4],
    /// `[радиус отсечения, насыщенность стекла, мягкость края пути, 0]`.
    pub extra: [f32; 4],
    /// Глиф: uv в атласе `[u0, v0, u1, v1]`; тень: исходная фигура
    /// `[x, y, w, h]`; путь: преобразование `[ox, oy, масштаб, режим]`.
    pub uv: [f32; 4],
    /// Путь: `[первый сегмент, число сегментов, 0, 0]`.
    pub seg: [f32; 4],
}

/// Пакет инстансов. Перед пакетом с `capture = true` рендерер снимает
/// копию уже нарисованного кадра и строит из неё размытую пирамиду —
/// её сэмплируют инстансы [`Kind::Backdrop`] (настоящий backdrop-filter).
#[derive(Clone, Copy, Debug, PartialEq, Default)]
#[repr(C)]
pub struct Batch {
    /// Первый инстанс пакета.
    pub start: u32,
    /// Конец диапазона (не включая).
    pub end: u32,
    /// 1 — снять задний план перед отрисовкой пакета.
    pub capture: u32,
    /// Ключ кэша: ненулевой ключ означает «содержимое статично, пока ключ
    /// не изменился» (обои). Рендереры кэшируют такой пакет в текстуру.
    pub cache_key: u32,
}

/// Готовый кадр.
#[derive(Clone, Debug, Default)]
pub struct Frame {
    /// Размер цели в физических пикселях.
    pub width: u32,
    /// Высота цели в физических пикселях.
    pub height: u32,
    /// Цвет очистки (surface-base темы).
    pub clear: [f32; 4],
    /// Все примитивы кадра в порядке отрисовки.
    pub instances: alloc::vec::Vec<Instance>,
    /// Разбиение инстансов на пакеты.
    pub batches: alloc::vec::Vec<Batch>,
    /// Отрезки векторных путей `[x0, y0, x1, y1]` в единицах иконки.
    pub segments: alloc::vec::Vec<[f32; 4]>,
}

impl Frame {
    /// Пустой кадр заданного размера.
    pub fn new(width: u32, height: u32) -> Frame {
        Frame { width, height, ..Default::default() }
    }

    /// Очищает кадр, сохраняя выделенную память (без аллокаций на кадр).
    pub fn reset(&mut self, width: u32, height: u32, clear: [f32; 4]) {
        self.width = width;
        self.height = height;
        self.clear = clear;
        self.instances.clear();
        self.batches.clear();
        self.segments.clear();
    }
}

